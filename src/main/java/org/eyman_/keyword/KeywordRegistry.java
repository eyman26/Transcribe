package org.eyman_.keyword;

import org.bukkit.configuration.ConfigurationSection;
import org.bukkit.configuration.file.YamlConfiguration;
import org.bukkit.permissions.Permission;
import org.bukkit.permissions.PermissionDefault;
import org.bukkit.plugin.PluginManager;
import org.bukkit.plugin.java.JavaPlugin;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.time.Duration;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.TreeSet;
import java.util.stream.Stream;

public final class KeywordRegistry {

    public record Snapshot(Map<String, KeywordDefinition> byForm,
                           Map<String, KeywordDefinition> byId,
                           List<String> grammar,
                           List<String> problems,
                           int disabledCount) {
        public static final Snapshot EMPTY = new Snapshot(Map.of(), Map.of(), List.of(), List.of(), 0);
    }

    private static final String TEMPLATE = """
            # Generated by /transcribe add keyword. Every option is documented in keywords/example.yml.
            enabled: true
            keyword: "{{word}}"
            aliases: []
            permission: ""
            min-confidence: 0.60
            cooldown-seconds: 3
            actions:
              executor: CONSOLE
              commands: []
            hooks:
              mythicmobs:
                enabled: false
                skill: ""
              nexo:
                enabled: false
                executor: CONSOLE
                commands: []
              itemsadder:
                enabled: false
                executor: CONSOLE
                commands: []
              oraxen:
                enabled: false
                executor: CONSOLE
                commands: []
            """;

    private final JavaPlugin plugin;
    private final Path folder;
    private volatile Snapshot current = Snapshot.EMPTY;

    public KeywordRegistry(JavaPlugin plugin) {
        this.plugin = plugin;
        this.folder = plugin.getDataFolder().toPath().resolve("keywords").toAbsolutePath().normalize();
    }

    public Snapshot snapshot() {
        return current;
    }

    public Optional<KeywordDefinition> find(String spokenForm) {
        return Optional.ofNullable(current.byForm().get(spokenForm));
    }

    public Snapshot scan() {
        List<String> problems = new ArrayList<>();
        try {
            seedExampleIfFolderMissing();
        } catch (IOException e) {
            problems.add("Could not create keywords folder: " + e.getMessage());
            return new Snapshot(Map.of(), Map.of(), List.of(), problems, 0);
        }

        Map<String, KeywordDefinition> byId = new LinkedHashMap<>();
        Map<String, KeywordDefinition> byForm = new HashMap<>();
        int disabled = 0;

        List<Path> files;
        try (Stream<Path> stream = Files.list(folder)) {
            files = stream.filter(p -> p.getFileName().toString().toLowerCase(Locale.ROOT).endsWith(".yml"))
                    .sorted().toList();
        } catch (IOException e) {
            problems.add("Could not list keywords folder: " + e.getMessage());
            return new Snapshot(Map.of(), Map.of(), List.of(), problems, 0);
        }

        for (Path file : files) {
            String name = file.getFileName().toString();
            KeywordDefinition def;
            try {
                def = parse(file);
            } catch (Exception e) {
                problems.add(name + ": " + e.getMessage());
                continue;
            }
            if (byId.containsKey(def.id())) {
                problems.add(name + ": duplicate of '" + def.word() + "' (already defined) - skipped.");
                continue;
            }
            byId.put(def.id(), def);
            if (!def.enabled()) {
                disabled++;
                continue;
            }
            boolean clash = false;
            for (String form : def.spokenForms()) {
                KeywordDefinition owner = byForm.get(form);
                if (owner != null) {
                    problems.add(name + ": spoken form '" + form + "' is already used by '" + owner.word() + "'.");
                    clash = true;
                }
            }
            if (!clash) {
                def.spokenForms().forEach(f -> byForm.put(f, def));
            }
        }

        return new Snapshot(Map.copyOf(byForm), Map.copyOf(byId),
                List.copyOf(new TreeSet<>(byForm.keySet())), List.copyOf(problems), disabled);
    }

    public void install(Snapshot snapshot) {
        PluginManager pm = plugin.getServer().getPluginManager();
        PermissionDefault parsed = null;
        try {
            parsed = PermissionDefault.getByName(plugin.getConfig().getString("permissions.keyword-default", "TRUE"));
        } catch (RuntimeException ignored) {
        }
        PermissionDefault permDefault = parsed != null ? parsed : PermissionDefault.TRUE;

        for (KeywordDefinition k : snapshot.byId().values()) {
            if (pm.getPermission(k.permission()) == null) {
                Permission p = new Permission(k.permission(),
                        "Allows speaking '" + k.word() + "' to trigger its actions", permDefault);
                pm.addPermission(p);
                // custom nodes aren't children of the wildcard
                if (k.permission().equals(defaultPermission(k.id()))) {
                    p.addParent("transcribe.keyword.*", true);
                }
            }
        }
        this.current = snapshot;
    }

    static String defaultPermission(String id) {
        return "transcribe.keyword." + id;
    }

    public Path createKeywordFile(String rawForm) throws IOException {
        String word = WordParser.validate(rawForm);
        Files.createDirectories(folder);
        Path file = folder.resolve(WordParser.toId(word) + ".yml").normalize();
        if (!file.startsWith(folder)) {
            throw new IllegalArgumentException("Illegal file name.");
        }
        Files.writeString(file, TEMPLATE.replace("{{word}}", word), StandardCharsets.UTF_8,
                StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
        return file;
    }

    private void seedExampleIfFolderMissing() throws IOException {
        if (Files.isDirectory(folder)) {
            return;
        }
        Files.createDirectories(folder);
        plugin.saveResource("keywords/example.yml", false);
    }

    private KeywordDefinition parse(Path file) throws Exception {
        YamlConfiguration yaml = new YamlConfiguration();
        yaml.load(file.toFile());

        String word = WordParser.validate(yaml.getString("keyword"));
        String id = WordParser.toId(word);

        List<String> aliases = new ArrayList<>();
        for (String raw : yaml.getStringList("aliases")) {
            String alias = WordParser.validate(raw);
            if (!alias.equals(word) && !aliases.contains(alias)) {
                aliases.add(alias);
            }
        }

        String configuredPermission = yaml.getString("permission", "").strip();
        String permission = configuredPermission.isEmpty() ? defaultPermission(id) : configuredPermission;
        float minConfidence = (float) Math.max(0.0, Math.min(1.0, yaml.getDouble("min-confidence", 0.0)));
        Duration cooldown = Duration.ofMillis(
                Math.max(0L, Math.round(yaml.getDouble("cooldown-seconds", 0.0) * 1000.0)));

        KeywordDefinition.Executor executor;
        try {
            executor = KeywordDefinition.Executor.valueOf(
                    yaml.getString("actions.executor", "CONSOLE").toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException e) {
            throw new IllegalArgumentException("actions.executor must be CONSOLE or PLAYER");
        }
        List<String> commands = List.copyOf(yaml.getStringList("actions.commands"));

        Map<String, KeywordDefinition.HookConfig> hooks = new LinkedHashMap<>();
        ConfigurationSection hookRoot = yaml.getConfigurationSection("hooks");
        if (hookRoot != null) {
            for (String key : hookRoot.getKeys(false)) {
                ConfigurationSection section = hookRoot.getConfigurationSection(key);
                if (section == null) {
                    continue;
                }
                String hookId = key.toLowerCase(Locale.ROOT);
                hooks.put(hookId, new KeywordDefinition.HookConfig(
                        hookId, section.getBoolean("enabled", false), Map.copyOf(section.getValues(false))));
            }
        }

        return new KeywordDefinition(id, word, yaml.getBoolean("enabled", true), List.copyOf(aliases),
                permission, minConfidence, cooldown, new KeywordDefinition.Actions(executor, commands), Map.copyOf(hooks));
    }
}
